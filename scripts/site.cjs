'use strict';
// Builds the GitHub Pages files from the localized copy and the bundled English privacy policy.
const fs = require('node:fs');
const path = require('node:path');
const locales = require('../content/site-locales.cjs');
const root = path.resolve(__dirname, '..');
const content = path.join(root, 'content');
const site = path.join(root, 'dist');
const home = 'https://sakha1370.github.io/tivona/';
const minimumChromeVersion = '109';
const store = 'https://chromewebstore.google.com/detail/aeoijkdjmndfjkkalijcjafcmhmloemh';
const mail = 'mailto:sakha1370@gmail.com';

const localeUrl = locale => home + (locale.path ? locale.path + '/' : '');
const alternates = [...locales.map(locale => [locale.tag, localeUrl(locale)]), ['x-default', home]];
const escape = value => value.replace(/[&<>"]/g, char => ({
  '&': '&amp;', '<': '&lt;', '>': '&gt;', '"': '&quot;'
})[char]);
const assetFolder = locale => 'assets/' + (locale.path || 'en') + '/';
const direction = locale => locale.rtl ? 'rtl' : 'ltr';

function siteLanding(locale, copy) {
  const url = localeUrl(locale);
  const prefix = locale.path ? '../' : '';
  const images = prefix + assetFolder(locale);
  const imageHeight = locale.imageHeight || 720;
  const imageUrl = home + assetFolder(locale) + 'dashboard.webp';
  const install = new URL(store);
  install.search = new URLSearchParams({
    hl: locale.storeLang || locale.tag,
    utm_source: 'tivona_site',
    utm_medium: 'referral',
    utm_campaign: 'homepage',
    utm_content: locale.path || 'en'
  });
  const storeLink = store + '?hl=' + install.searchParams.get('hl');
  const policy = `<a href="${home}privacy.html" hreflang="en">${escape(copy.policy)}</a>`;
  const help = escape(copy.help)
    .replace('{email}', `<a href="${mail}">${escape(copy.emailLink)}</a>`)
    .replace('{store}', `<a href="${storeLink}">${escape(copy.storeLink)}</a>`);
  const schema = {
    '@context': 'https://schema.org',
    '@type': 'SoftwareApplication',
    name: 'Tivona',
    url,
    description: copy.description,
    applicationCategory: 'ProductivityApplication',
    softwareRequirements: 'Chrome ≥ ' + minimumChromeVersion,
    installUrl: store,
    image: imageUrl,
    offers: { '@type': 'Offer', price: 0, priceCurrency: 'USD' }
  };
  const languageLinks = locales.map(other => {
    const href = localeUrl(other);
    const current = other.code === locale.code ? ' aria-current="page"' : '';
    return `          <li><a href="${href}" hreflang="${other.tag}" lang="${other.tag}" dir="${direction(other)}"${current}>${escape(other.name)}</a></li>`;
  }).join('\n');
  const figure = (name, priority) => {
    const image = copy[name];
    return `      <figure class="preview">
        <img src="${images}${name}.webp" srcset="${images}${name}-640.webp 640w, ${images}${name}.webp 1280w" sizes="(max-width: 868px) calc(100vw - 48px), 820px" width="1280" height="${imageHeight}" ${priority} decoding="async" alt="${escape(image.alt)}">
        <figcaption>${escape(image.caption)}</figcaption>
      </figure>`;
  };
  const cards = items => items.map(([heading, body]) => `        <div>
          <h3>${escape(heading)}</h3>
          <p>${escape(body)}</p>
        </div>`).join('\n');

  return `<!doctype html>
<html lang="${locale.tag}" dir="${direction(locale)}">
<!-- Generated by npm run site from scripts/site-copy/. -->
<head>
  <meta charset="utf-8">
  <meta name="viewport" content="width=device-width, initial-scale=1">
  <title>${escape(copy.title)}</title>
  <meta name="description" content="${escape(copy.description)}">
  <link rel="canonical" href="${url}">
${alternates.map(([tag, href]) => `  <link rel="alternate" hreflang="${tag}" href="${href}">`).join('\n')}
  <script>
    (() => {
      const oldPrefix = '/dial';
      if (location.hostname !== 'sakha1370.github.io') return;
      if (location.pathname !== oldPrefix && !location.pathname.startsWith(oldPrefix + '/')) return;
      const destination = 'https://sakha1370.github.io/tivona' + (location.pathname.slice(oldPrefix.length) || '/');
      location.replace(destination + location.search + location.hash);
    })();
  </script>
  <meta property="og:type" content="website">
  <meta property="og:site_name" content="Tivona">
  <meta property="og:locale" content="${locale.social}">
  <meta property="og:title" content="${escape(copy.title)}">
  <meta property="og:description" content="${escape(copy.shareDescription)}">
  <meta property="og:url" content="${url}">
  <meta property="og:image" content="${imageUrl}">
  <meta property="og:image:width" content="1280">
  <meta property="og:image:height" content="${imageHeight}">
  <meta property="og:image:alt" content="${escape(copy.dashboard.alt)}">
  <meta name="twitter:card" content="summary_large_image">
  <link rel="icon" type="image/png" href="${prefix}assets/tivona-icon.png">
  <link rel="stylesheet" href="${prefix}help.css">
  <link rel="stylesheet" href="${prefix}landing.css">
  <script type="application/ld+json">
${JSON.stringify(schema, null, 2).replace(/</g, '\\u003c')}
  </script>
</head>
<body>
  <a class="skip-link" href="#main">${escape(copy.skip)}</a>
  <header class="site-header">
    <nav aria-label="${escape(copy.navigation)}">
      <a href="#features">${escape(copy.featuresLink)}</a>
      <a href="#help">${escape(copy.helpLink)}</a>
      <details class="language-picker">
        <summary>${escape(copy.language)}</summary>
        <ul class="language-links">
${languageLinks}
        </ul>
      </details>
    </nav>
  </header>
  <main id="main" class="landing" tabindex="-1">
    <div class="hero">
      <h1>${escape(copy.headline)}</h1>
      <p>${escape(copy.intro)}</p>
      <p><a class="cta" id="install" href="${escape(install.href)}">${escape(copy.install)}</a></p>
      <p class="muted">${escape(copy.installNote)}</p>
${figure('dashboard', 'fetchpriority="high"')}
    </div>

    <section aria-labelledby="features">
      <h2 id="features">${escape(copy.featuresTitle)}</h2>
      <div class="features">
${cards(copy.features)}
      </div>
${figure('calendars', 'loading="lazy"')}
      <p>${escape(copy.more)}</p>
    </section>

    <section aria-labelledby="getting-started">
      <h2 id="getting-started">${escape(copy.startTitle)}</h2>
      <ol>
${copy.steps.map(step => `        <li>${escape(step)}</li>`).join('\n')}
      </ol>
    </section>

    <section class="faq" aria-labelledby="faq">
      <h2 id="faq">${escape(copy.faqTitle)}</h2>
${cards(copy.faq)}
    </section>

    <section aria-labelledby="privacy">
      <h2 id="privacy">${escape(copy.privacyTitle)}</h2>
      <p>${escape(copy.offline)}</p>
      <p>${escape(copy.privacy)} ${policy}</p>
    </section>

    <section aria-labelledby="help">
      <h2 id="help">${escape(copy.helpTitle)}</h2>
      <p>${help}</p>
    </section>
  </main>
  <footer class="site-footer">
    <p class="muted">${escape(copy.credits)}</p>
    ${policy}
  </footer>
</body>
</html>
`;
}

function siteSitemap() {
  const links = alternates.map(([tag, url]) => `    <xhtml:link rel="alternate" hreflang="${tag}" href="${url}" />`).join('\n');
  return `<?xml version="1.0" encoding="UTF-8"?>
<urlset xmlns="http://www.sitemaps.org/schemas/sitemap/0.9" xmlns:xhtml="http://www.w3.org/1999/xhtml">
${locales.map(locale => `  <url>
    <loc>${localeUrl(locale)}</loc>
${links}
  </url>`).join('\n')}
  <url>
    <loc>${home}privacy.html</loc>
  </url>
</urlset>
`;
}

function siteRobots() {
  return `User-agent: *\nAllow: /\n\nSitemap: ${home}sitemap.xml\n`;
}

// The bundled policy as the website serves it.
function sitePrivacy(bundled) {
  const out = bundled
    .replace('</head>', [
      '',
      '<meta name="description" content="Learn where Tivona stores dashboard data, when it contacts online services and how to manage sync, backups and optional usage sharing.">',
      `<link rel="canonical" href="${home}privacy.html">`,
      '<link rel="icon" type="image/png" href="assets/tivona-icon.png">',
      '</head>'
    ].join('\n'))
    .replace('<a href="newtab.html">Back to Tivona</a>', '<a href="./">Tivona</a>')
    .replace('<a href="support.html">Help & feedback</a>', '<a href="./#help">Help &amp; feedback</a>')
    .replace(/<a href="#fa" lang="fa">[^<]*<\/a>/, '')
    .replace(/(\r?\n)(?:\r?\n)*<section id="fa"[\s\S]*?<\/section>\r?\n/, '$1');
  if (out.includes('newtab.html') || out.includes('support.html')) throw new Error('privacy.html has extension-only links');
  if (/lang="fa"|id="fa"/.test(out)) throw new Error('the Persian section was not removed from the site copy');
  return out;
}

if (require.main === module) {
  for (const locale of locales) {
    const dir = path.join(site, locale.path);
    const copy = require('../content/site-copy/' + locale.code + '.json');
    fs.mkdirSync(dir, { recursive: true });
    fs.writeFileSync(path.join(dir, 'index.html'), siteLanding(locale, copy));
  }
  fs.writeFileSync(path.join(site, 'sitemap.xml'), siteSitemap());
  fs.writeFileSync(path.join(site, 'robots.txt'), siteRobots());
  fs.mkdirSync(path.join(site, 'fonts'), { recursive: true });
  fs.writeFileSync(path.join(site, 'privacy.html'), sitePrivacy(fs.readFileSync(path.join(content, 'privacy.html'), 'utf8')));
  fs.copyFileSync(path.join(content, 'help.css'), path.join(site, 'help.css'));
  fs.copyFileSync(path.join(content, 'landing.css'), path.join(site, 'landing.css'));
  fs.copyFileSync(path.join(content, 'fonts', 'Vazirmatn-NL-wght.woff2'), path.join(site, 'fonts', 'Vazirmatn-NL-wght.woff2'));
  fs.copyFileSync(path.join(content, 'fonts', 'Vazirmatn-OFL.txt'), path.join(site, 'fonts', 'Vazirmatn-OFL.txt'));
  fs.cpSync(path.join(content, 'assets'), path.join(site, 'assets'), { recursive: true });
  fs.copyFileSync(path.join(content, 'uninstall.html'), path.join(site, 'uninstall.html'));
  for (const name of fs.readdirSync(content).filter(name => /^google[a-z0-9]+\.html$/.test(name))) {
    fs.copyFileSync(path.join(content, name), path.join(site, name));
  }
  console.log(`Generated ${locales.length} localized pages, shared assets, privacy policy, sitemap and robots.txt in dist/.`);
}

module.exports = { siteLanding, sitePrivacy, siteSitemap, siteRobots };
